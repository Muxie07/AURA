from pydantic import BaseModel, Field


class Usage(BaseModel):
    """Normalized token usage tracking."""
    prompt_tokens: int = Field(default=0, description="Tokens used in the prompt.")
    completion_tokens: int = Field(default=0, description="Tokens generated by the model.")
    total_tokens: int = Field(default=0, description="Total tokens used (prompt + completion).")
    estimated_cost: float | None = Field(default=None, description="Estimated cost in USD.")
